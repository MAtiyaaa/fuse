package io.github.matiyaaa.fuse.launch.settings

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

/** Configs of one setting a line, as the Quake engines, EDGE-Classic and sm64coopdx write them, changed in place. */
class WordsTextTest {
    @Test
    fun aQuakeConfigsSetaLinesAreReadAndChangedInPlace() {
        val cfg = "// generated by quake, do not modify\nunbindall\nbind TAB \"+scores\"\nseta r_mode \"-2\"\nseta com_maxfps \"125\"\nset cl_paused \"0\"\n"
        val w = WordsText(cfg, "seta")
        assertEquals(listOf("-2"), w.values("", "r_mode"))
        assertEquals(listOf("125"), w.values("", "COM_MAXFPS"), "a console variable's name in any case")
        assertEquals(listOf("0"), w.values("", "cl_paused"), "set lines are read too")
        assertEquals(emptyList(), w.values("", "bind"), "a binding isn't a setting")
        w.set("", "r_mode", "4")
        w.set("", "r_fullscreen", "1")
        assertEquals(
            "// generated by quake, do not modify\nunbindall\nbind TAB \"+scores\"\nseta r_mode \"4\"\nseta com_maxfps \"125\"\nset cl_paused \"0\"\nseta r_fullscreen \"1\"\n",
            w.toString(),
            "every value quoted, as Cvar_WriteVariables writes it; a new one last",
        )
        assertTrue(w.removeKey("", "r_fullscreen"))
        assertFalse(w.removeKey("", "r_fullscreen"))
    }

    @Test
    fun theLastLineANameIsSetOnIsTheOneTheEngineEndsWithAndTheOneChanged() {
        val w = WordsText("seta s_volume \"0.5\"\nseta s_volume \"0.8\"\n", "seta")
        assertEquals(listOf("0.8"), w.values("", "s_volume"))
        w.set("", "s_volume", "1")
        assertEquals("seta s_volume \"0.5\"\nseta s_volume \"1\"\n", w.toString())
    }

    @Test
    fun edgeClassicsSlashedNamesKeepTheirTab() {
        val w = WordsText("/gamma\t\"0\"\n/music_volume\t\"0.15\"\n", WordsText.SLASH)
        assertEquals(listOf("0.15"), w.values("", "music_volume"))
        w.set("", "music_volume", "0.5")
        w.set("", "vsync", "1")
        assertEquals("/gamma\t\"0\"\n/music_volume\t\"0.5\"\n/vsync\t\"1\"\n", w.toString())
    }

    @Test
    fun aPaddedNameKeepsItsPaddingAndTextIsQuotedWhereItShouldBe() {
        val w = WordsText("screenblocks          10\nchat_macro0           \"No\"\n", isText = { it.startsWith("chat_") })
        w.set("", "screenblocks", "11")
        w.set("", "chat_macro0", "Yes")
        assertEquals("screenblocks          11\nchat_macro0           \"Yes\"\n", w.toString())
        // sm64coopdx writes its text as it is.
        val bare = WordsText("fullscreen false\ncoop_player_name Mario\n", bare = true)
        bare.set("", "coop_player_name", "Luigi")
        bare.set("", "fullscreen", "true")
        assertEquals("fullscreen true\ncoop_player_name Luigi\n", bare.toString())
    }

    @Test
    fun aValueTheEngineCantReadBackIsRefusedAndAFileWithoutSettingsHasNone() {
        val w = WordsText("")
        assertFalse(w.hasEntries())
        assertTrue(runCatching { w.set("", "name", "a\"b") }.isFailure)
        assertTrue(runCatching { w.set("Video", "x", "1") }.isFailure, "no sections")
        w.set("", "x", "1")
        assertEquals("x 1\n", w.toString())
        assertTrue(w.hasEntries())
    }
}
